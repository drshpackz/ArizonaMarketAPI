--- Возвращает число штук и признак «прочитано, а не выведено».
---
--- ⚠ ВТОРОЕ ЗНАЧЕНИЕ — НЕ УКРАШЕНИЕ. «Одна штука, потому что подписи нет» и
--- «одна штука, потому что подпись мы не поняли» — разные утверждения.
---
--- ⚠ `amount` ЗДЕСЬ НЕ УЧАСТВУЕТ, И ЭТО ИЗМЕРЕНО. В снимках 14.08.2026 у
--- предмета 9252 стоит `amount = 1` при подписи «909», у 10137 — `amount = 1`
--- при «643»: поле совпадает с количеством случайно. Считаем по подписи.

local M = {}

M.FILE_VERSION = "0.1.0"

function M.count(cell)
	if type(cell) ~= "table" then return 0, false end
	-- ⚠ ПУСТАЯ ПОДПИСЬ — ЭТО «ПОДПИСИ НЕТ», А НЕ «НЕ РАЗОБРАЛИ»: у одиночной
	-- вещи рисовать нечего, и она одна точно.
	if cell.text == nil or cell.text == "" then return 1, true end
	-- ⚠ ПОДПИСЬ СО СРОКОМ — НЕ КОЛИЧЕСТВО. «88 дней» числом объявил бы один
	-- абонемент восемьюдесятью восемью.
	if cell.time then return 1, false end
	local n = tonumber(cell.text)
	if n and n == math.floor(n) and n > 0 then return n, true end
	-- Подпись есть, а числом не читается («KD»). Вещь одна, но это ВЫВОД.
	return 1, false
end

return M
