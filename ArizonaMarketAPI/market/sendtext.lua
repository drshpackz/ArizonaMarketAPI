local M = {}

M.FILE_VERSION = "0.1.0"

--- Строка — как есть; таблица с полем-строкой `text` — это поле; иначе `nil`.
---
--- `nil` означает «не наше дело»: обработчик обязан пропустить такое сообщение
--- нетронутым, а не гадать о его содержимом.
function M.textOf(x)
	if type(x) == "string" then return x end
	if type(x) == "table" and type(x.text) == "string" then return x.text end
	return nil
end

return M
