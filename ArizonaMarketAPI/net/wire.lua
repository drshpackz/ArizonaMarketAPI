--- Конверт отправки: превращение куска журнала в тело запроса. ЧИСТАЯ часть.
---
--- Отдельно от `net/uplink.lua` по той же причине, по которой отдельно
--- `net/outbox.lua`: экранирование — это то, что ошибается молча. Испорченная
--- кавычка не роняет ни игру, ни сервер, она просто делает тело неразбираемым,
--- и увидеть это можно лишь в ответе сервера, то есть уже в игре.

local M = {}

M.FILE_VERSION = "0.1.0"

--- Версия конверта. Обязана совпадать с `UPLINK_V` на сервере: тот отвечает
--- отказом на чужую, а не молча толкует поля по своим правилам.
M.V = 1

--- ⚠ ЗДЕСЬ НЕЛЬЗЯ ВЗЯТЬ `jstr` ИЗ `lib/asilab/loot.lua`, И ЭТО НЕ НЕДОСМОТР.
--- Тот заменяет перевод строки ПРОБЕЛОМ — правильно для однострочной записи и
--- гибельно здесь: мы шлём кусок журнала, где `\n` разделяет записи. Заменив их
--- пробелами, мы отправили бы одну гигантскую строку, сервер отбросил бы её как
--- «не json», а курсор при этом ушёл бы вперёд. Потеря без единой ошибки.
local ESC = {
	['"']  = '\\"',
	['\\'] = '\\\\',
	['\n'] = '\\n',
	['\r'] = '\\r',
	['\t'] = '\\t',
	['\b'] = '\\b',
	['\f'] = '\\f',
}

--- Строка JSON вместе с кавычками.
---
--- Байты выше 0x7F проходят КАК ЕСТЬ: журнал уже в UTF-8, и наше дело —
--- не перекодировать его, а довезти. Управляющие символы ниже 0x20 экранируются
--- поимённо, остальные — через `\u00XX`: сырой управляющий байт внутри строки
--- JSON недопустим по стандарту, и разборщик на той стороне на нём остановится.
function M.escape(s)
	s = tostring(s)
	s = s:gsub('[%c"\\]', function(c)
		return ESC[c] or string.format('\\u%04x', string.byte(c))
	end)
	return '"' .. s .. '"'
end

--- Тело запроса. Поля те же, что читает маршрут `/api/uplink`.
---
--- `from` — АБСОЛЮТНОЕ смещение куска в файле игрока, `head` — отпечаток начала
--- файла. Оба нужны серверу, чтобы решить за нас: он ведёт курсор, а мы лишь
--- сообщаем, откуда взяли.
function M.envelope(file, from, head, chunk)
	return table.concat({
		'{"v":', tostring(M.V),
		',"file":', M.escape(file),
		',"from":', string.format("%d", math.floor(from or 0)),
		',"head":', M.escape(head or ""),
		',"chunk":', M.escape(chunk or ""),
		'}',
	})
end

--- Ответ сервера. Разбирается образцами, а не разборщиком JSON: полей четыре,
--- они наши, и зависимость ради них была бы дороже.
---
--- ⚠ `upto` ЧИТАЕТСЯ И ИЗ ОТКАЗА ТОЖЕ. При дыре сервер отвечает 409 и полем
--- `expect` — это не «повторите», а точное «шли с этого байта». Пропустить его
--- значит зациклиться на той же дыре навсегда.
function M.reply(text)
	text = tostring(text or "")
	local out = {
		upto     = tonumber(text:match('"upto"%s*:%s*(%d+)')),
		expect   = tonumber(text:match('"expect"%s*:%s*(%d+)')),
		accepted = tonumber(text:match('"accepted"%s*:%s*(%d+)')) or 0,
		skipped  = tonumber(text:match('"skipped"%s*:%s*(%d+)')) or 0,
		error    = text:match('"error"%s*:%s*"([^"]*)"'),
		-- Ответ самовыдачи. Токен — base64url, то есть буквы, цифры, `-` и `_`:
		-- кавычек в нём не бывает, и образец по «до кавычки» безопасен.
		token    = text:match('"token"%s*:%s*"([^"]*)"'),
		id       = text:match('"id"%s*:%s*"([^"]*)"'),
	}
	return out
end

--- Тело регистрации. `uid` необязателен: в игре его взять неоткуда, а
--- требовать число, которого у честного клиента нет, значит закрыть дверь
--- ровно перед ним — подделать его всё равно ничего не стоит.
function M.registration(nick, uid)
	local parts = { '{"v":', tostring(M.V), ',"nick":', M.escape(nick or '') }
	if tonumber(uid) and tonumber(uid) > 0 then
		parts[#parts + 1] = ',"uid":' .. string.format('%d', math.floor(tonumber(uid)))
	end
	parts[#parts + 1] = '}'
	return table.concat(parts)
end

--- ⚠ «ПРИНЯТО 0 ИЗ N» — ЭТО НОВОСТЬ, А НЕ ОТТЕНОК «ПРИНЯТО».
---
--- 08.08.2026 при переносе сбора потерялось поле `at`, и приёмник браковал
--- КАЖДУЮ находку. Обмен при этом шёл успешно: код 200, курсор двигался, в
--- сводке росло «отброшено». За час на сервер не легло ни одной находки, и
--- снаружи это выглядело как «данные пропали».
---
--- Разница принципиальная и потому считается отдельно: часть отброшенного —
--- обычное дело (чужие сетки, устаревшие строки), а ВСЁ отброшенное означает,
--- что клиент производит негодное. Первое — шум, второе — поломка.
---
--- Возвращает `nil`, если всё в порядке, либо строку с тем, что надо сказать.
--- Виноват ли в отступе САМ ФАЙЛ, или причина общая.
---
--- ⚠⚠ ЭТО РАЗЛИЧЕНИЕ СТОИЛО СПРАВОЧНИКУ БАКОВ СУТОК МОЛЧАНИЯ. Отступ бывает
--- двух совершенно разных природ:
---
---   * общий — квота отправителя (429), обрыв связи, сервер лёг. К конкретному
---     файлу это отношения не имеет: следующий в очереди получил бы то же самое;
---   * файла — сервер не принял именно эти строки.
---
--- Клиент откладывает файл после трёх неудач подряд, и это правильно: один
--- негодный файл иначе держит очередь вечно. Но записывать за файлом ОБЩИЙ
--- отказ — значит наказывать невиновного.
---
--- Так и вышло 15–16.08.2026 с `garbage/bins.jsonl`. Он сортируется последним
--- среди `garbage/*`, то есть очередь доходит до него с уже исчерпанной квотой
--- (60 запросов в минуту на отправителя). Три отказа 429 — файл отложен; в
--- следующей сессии всё повторялось. Справочник баков не уехал НИ РАЗУ, при
--- полностью исправном обмене по остальным потокам: сайт не знал о новых баках,
--- а в журнале стояло безобидное «файл отложен после 3 неудач».
---
--- Признак общей причины — код ответа, а не текст: 429 и «связи нет» (0).
function M.blameFile(code)
	code = tonumber(code) or 0
	if code == 429 then return false end   -- квота отправителя, не файла
	if code == 0 then return false end     -- связи нет вовсе
	return true
end

function M.rejection(rep)
	if type(rep) ~= "table" then return nil end
	local ok  = tonumber(rep.accepted) or 0
	local bad = tonumber(rep.skipped) or 0
	if bad == 0 then return nil end
	if ok > 0 then return nil end
	return ("сервер отбросил ВСЕ %d строк — клиент шлёт негодное"):format(bad)
end

--- Что делать при таком коде ответа. Решение вынесено сюда, потому что оно
--- РАЗНОЕ по смыслу, а не по числу, и проверяется на хосте.
---
---   `ok`     — принято, двигаем курсор;
---   `rewind` — сервер знает лучше, ставим курсор туда, куда он сказал;
---   `stop`   — повторять бессмысленно, нужен человек (нет токена, чужая версия);
---   `retry`  — временно, отступаем и пробуем снова.
function M.verdict(code, reply)
	code = tonumber(code) or 0
	if code == 200 then return "ok" end
	if code == 409 then return "rewind" end
	-- 401 и 403 — про права, 400 и 413 — про то, что мы шлём. Повтор того же
	-- куска даст тот же ответ, и молотить им сервер бессмысленно.
	if code == 401 or code == 403 or code == 400 or code == 413 then return "stop" end
	-- 429 — «слишком часто». Это ровно тот случай, ради которого есть отступ.
	if code == 429 then return "retry" end
	-- ⚠ ПРИЧИНА ОТСТУПА ВАЖНА, А НЕ ТОЛЬКО САМ ОТСТУП. См. `M.blameFile`.
	if code >= 500 then return "retry" end
	if code <= 0 then return "retry" end          -- сеть не ответила вовсе
	return "retry"
end

return M
