--- Очередь досылки: какой кусок какого журнала уходит на сайт следующим.
---
--- Решение и обоснование целиком —
--- `docs/cdevpowers/specs/2026-08-08-loot-uplink-design.md`. Здесь только то,
--- без чего нельзя читать код.
---
--- ⚠ ЭТОТ МОДУЛЬ НЕ ЧИТАЕТ ФАЙЛОВ И НЕ ХОДИТ В СЕТЬ. Он получает уже прочитанный
--- хвост строкой и отдаёт решение. Разделение не ради красоты: логика доставки —
--- границы строк, курсор, отпечаток, отступ после отказа — это ровно то, что
--- ошибается молча и проверяется на хосте за миллисекунды. Смешай её с `io` и
--- сокетом, и единственным способом проверить станет живая игра.
---
--- ⚠ ОТПРАВИТЕЛЬ — ХВОСТОВОЙ ЧИТАТЕЛЬ ЖУРНАЛА, А НЕ ВРЕЗКА В СБОРЩИК. Он не
--- трогает `asilab-loot.lua` и вообще ничего не знает о том, кто пишет файлы.
--- Отсюда три свойства: сбор не зависит от сети, падение не теряет ничего
--- (данные на диске раньше, чем отправка о них узнала), а накопленное за прошлые
--- дни досылается тем же кодом — это просто файл, у которого курсор на нуле.

local M = {}

M.FILE_VERSION = "0.1.0"

--- Сколько байт и строк уходит за одну отправку.
---
--- ⚠ Предела ДВА, и меньший из них решает. Байты защищают чужой сервер и наш
--- канал, строки — приёмник: у него свой предел в 5000 находок за запрос, и
--- упереться в чужой предел мы не должны никогда. 500 — с запасом в десять раз.
M.MAX_BYTES = 262144
M.MAX_LINES = 500

--- Сколько байт от начала файла берётся под отпечаток.
M.HEAD_BYTES = 4096

--- Отступ после неудачи: 1, 2, 4 … и потолок в пять минут.
---
--- Потолок обязателен. Без него отступ уходит в часы, и человек, починивший
--- сеть, ждёт следующей попытки дольше, чем длилась поломка.
M.BACKOFF_BASE = 1
M.BACKOFF_MAX  = 300

-- --- Отпечаток файла --------------------------------------------------------
--
-- ⚠ ЗАЧЕМ ОН ВООБЩЕ НУЖЕН. Курсор — это байтовое смещение, и смысл оно имеет
-- только внутри ТОГО ЖЕ файла. Игрок переустановил игру, стёр журнал, начал
-- день заново — смещение из прошлой жизни указывает в середину чужого текста, и
-- дальше уходит мусор, который выглядит как данные.
--
-- Отпечаток отвечает на один вопрос: тот ли это файл. От подделки он не
-- защищает и защищать не обязан — злоумышленнику незачем обманывать СВОЙ же
-- курсор. Поэтому здесь простая свёртка, а не md5: она не тянет зависимость и
-- считается на месте.

--- Свёртка РОВНО первых `HEAD_BYTES` байт. Файл короче — отпечатка НЕТ.
---
--- ⚠ ЭТО ИСПРАВЛЕНИЕ ЖИВОГО ПРОГОНА 08.08.2026, И ОШИБКА БЫЛА В СЛОВЕ
--- «НАМЕРЕННО». Прежняя редакция брала «первые HEAD_BYTES или сколько есть» и
--- подмешивала в результат ДЛИНУ взятого. На большом файле это работало, а на
--- коротком отпечаток менялся при КАЖДОЙ дозаписи — то есть журнал, которому
--- ещё нет четырёх килобайт, при каждой отправке выглядел ДРУГИМ файлом. Курсор
--- сбрасывался в ноль, и всё уходило заново.
---
--- Наблюдение, которым это поймано: `stalls.jsonl` — 7 строк в игре и 15 на
--- сервере (8 повторов), `snapshots.jsonl` — 9 и 25 (16 повторов), а
--- `cards.jsonl` на 31 КБ — 174 и 174, повторов НОЛЬ. Ровно граница в 4 КБ.
---
--- Отпечаток обязан быть НЕИЗМЕННЫМ при дозаписи — в этом весь его смысл.
--- Поэтому теперь: есть 4 КБ — считаем по ним и только по ним; нет — пустая
--- строка, то есть «мнения не имею», и проверка подмены просто не применяется.
--- Риск при этом ровно один: короткий файл заменили другим коротким, и мы не
--- заметили. Цена — несколько лишних строк, которые дедупликация цены снимет.
--- Цена прежнего поведения была выше: повторы при каждой отправке.
function M.fingerprint(text)
	if type(text) ~= "string" or #text < M.HEAD_BYTES then return "" end
	local h = 2166136261
	for i = 1, M.HEAD_BYTES do
		-- Умножение на 31 не выводит h за 2^37, а это ещё точно представимо
		-- в double. Брать множитель крупнее — значит терять младшие биты молча.
		h = (h * 31 + string.byte(text, i)) % 4294967296
	end
	return string.format("%08x", h)
end

-- --- Состояние --------------------------------------------------------------

function M.newState()
	return { v = 1, files = {} }
end

--- Запись о файле. Отсутствующая — это «не слали ничего», а не ошибка.
function M.entry(state, name)
	local e = state and state.files and state.files[name]
	if e then return e end
	return { sent = 0, head = "", lines = 0 }
end

-- --- Где кончается отправляемый кусок ----------------------------------------

--- Отрезает от хвоста ЦЕЛЫЕ строки в пределах обоих ограничений.
---
--- `tail` — байты файла, начинающиеся с абсолютного смещения `from`.
---
--- ⚠ ГЛАВНОЕ ЗДЕСЬ: НИКОГДА НЕ ОТДАВАТЬ ПОСЛЕДНЮЮ СТРОКУ БЕЗ `\n`. Игра пишет в
--- тот же файл, и хвост запросто окажется половиной записи. Отправить её — это
--- не «немного мусора»: курсор сдвинется за середину записи, и вторая её
--- половина уйдёт следующим куском как отдельная строка. Обе записи потеряны, и
--- ни одна проверка на сервере этого не заметит — там просто битый JSON.
---
--- Возвращает таблицу: `chunk`, `upto` (новое абсолютное смещение), `lines`,
--- `oversize`.
function M.cut(tail, from, opts)
	opts = opts or {}
	local maxBytes = opts.maxBytes or M.MAX_BYTES
	local maxLines = opts.maxLines or M.MAX_LINES
	from = from or 0

	local res = { chunk = "", upto = from, lines = 0, oversize = false }
	if type(tail) ~= "string" or tail == "" then return res end

	local cut, lines, pos = 0, 0, 1
	while lines < maxLines do
		local nl = string.find(tail, "\n", pos, true)
		if not nl or nl > maxBytes then break end
		cut, lines, pos = nl, lines + 1, nl + 1
	end

	if cut == 0 then
		-- Ни одной целой строки. Причин две, и они требуют РАЗНЫХ действий:
		-- «строка ещё пишется» (ждём) и «строка не влезает никогда» (её надо
		-- пропустить осознанно и посчитать, иначе очередь встанет навсегда).
		local nl = string.find(tail, "\n", 1, true)
		if (nl and nl > maxBytes) or (not nl and #tail >= maxBytes) then
			res.oversize = true
		end
		return res
	end

	res.chunk = string.sub(tail, 1, cut)
	res.upto  = from + cut
	res.lines = lines
	return res
end

-- --- Что слать следующим ------------------------------------------------------

--- Выбирает файл с недосланным хвостом.
---
--- `files` — список `{ name = , size = }`. Порядок обхода задаётся ИМЕНЕМ, а не
--- порядком в списке: имена журналов — даты, и по ним старое уходит раньше
--- нового. Читатель каталога порядка не гарантирует, а очередь, зависящая от
--- него, ведёт себя по-разному на разных машинах.
---
--- `shrunk` — файл СТАЛ КОРОЧЕ курсора. Это не «нечего слать», а сигнал: файл
--- подменён или обрезан, и звать надо `reset`, сверив отпечаток.
--- `skip` — имена, которые пропустить. Без него ОДИН негодный файл кладёт весь
--- канал, и это не выдумка: 15.08.2026 `garbage/bins.jsonl` оказался записан в
--- CP1251 вместо UTF-8, тело запроса перестало быть годным JSON, а поскольку по
--- алфавиту он стоит раньше всех `loot/*`, очередь выбирала его КАЖДЫЙ круг.
--- Итог — 21 КБ находок о лавках и 130 КБ снимков не уезжали пять часов, и
--- снаружи это выглядело как «синхронизация не работает».
---
--- ⚠ ПРОПУСК ОБЯЗАН БЫТЬ ВРЕМЕННЫМ И ГРОМКИМ. Он не чинит негодный файл — он
--- лишь не даёт ему держать остальных; решение «отложить» принимает вызывающий,
--- считает и называет вслух.
function M.plan(state, files, skip)
	if type(files) ~= "table" then return nil end
	skip = skip or {}

	local names = {}
	for _, f in ipairs(files) do
		if type(f) == "table" and type(f.name) == "string" then names[#names + 1] = f end
	end
	table.sort(names, function(a, b) return a.name < b.name end)

	for _, f in ipairs(names) do
		if not skip[f.name] then
			local e = M.entry(state, f.name)
			local size = tonumber(f.size) or 0
			if size < e.sent then
				return { name = f.name, from = e.sent, size = size, shrunk = true }
			end
			if size > e.sent then
				return { name = f.name, from = e.sent, size = size, shrunk = false }
			end
		end
	end
	return nil
end

--- Сколько всего осталось дослать. Число нужно человеку: «отправка включена» и
--- «отправка догнала» — разные утверждения, и второе иначе не проверить.
function M.pending(state, files)
	local bytes, count = 0, 0
	for _, f in ipairs(files or {}) do
		if type(f) == "table" and type(f.name) == "string" then
			local left = (tonumber(f.size) or 0) - M.entry(state, f.name).sent
			if left > 0 then
				bytes = bytes + left
				count = count + 1
			end
		end
	end
	return { bytes = bytes, files = count }
end

-- --- Подтверждение и сброс ----------------------------------------------------

--- Двигает курсор. Звать ТОЛЬКО после ответа сервера.
---
--- ⚠ Не после отправки — после подтверждения. Разрыв на полпути между этими
--- двумя точками стоит ровно один кусок журнала, и заметить пропажу нечем:
--- на сервере его нет, а у отправителя он числится посланным.
function M.ack(state, name, upto, lines, head)
	state = state or M.newState()
	state.files = state.files or {}
	local e = state.files[name] or { sent = 0, head = "", lines = 0 }
	if upto > e.sent then e.sent = upto end
	e.lines = (e.lines or 0) + (lines or 0)
	if head and head ~= "" then e.head = head end
	state.files[name] = e
	return state
end

--- Курсор в ноль: файл оказался другим. Счётчик строк тоже обнуляется — он
--- описывает ЭТОТ файл, а не отправителя вообще.
function M.reset(state, name, head)
	state = state or M.newState()
	state.files = state.files or {}
	state.files[name] = { sent = 0, head = head or "", lines = 0 }
	return state
end

--- Совпадает ли отпечаток с запомненным.
---
--- ⚠ ПУСТОЙ ОТПЕЧАТОК С ЛЮБОЙ СТОРОНЫ — ЭТО «МНЕНИЯ НЕ ИМЕЮ», А НЕ
--- РАСХОЖДЕНИЕ. Пустым он бывает дважды: файл мы ещё не видели (первый заход) и
--- файл короче четырёх килобайт (считать не по чему). Прими мы пустоту за
--- несовпадение — короткий журнал сбрасывал бы курсор при каждой отправке, и мы
--- получили бы ровно те повторы, ради устранения которых это и написано.
function M.sameFile(state, name, head)
	local was = M.entry(state, name).head
	if was == nil or was == "" then return true end
	if head == nil or head == "" then return true end
	return was == head
end

-- --- Отступ после отказа ------------------------------------------------------

--- Секунды до следующей попытки. `fails` — сколько подряд не удалось.
function M.backoff(fails)
	fails = tonumber(fails) or 0
	if fails < 1 then return 0 end
	local d = M.BACKOFF_BASE * 2 ^ (fails - 1)
	if d > M.BACKOFF_MAX then d = M.BACKOFF_MAX end
	return d
end

-- --- Хранение состояния -------------------------------------------------------
--
-- Свой разбор, а не `cjson`, ровно по одной причине: формат здесь НАШ и
-- фиксированный, а зависимость в модуле, который обязан работать раньше всего
-- остального, стоит дороже двадцати строк. Тот же довод, по которому `loot.lua`
-- разбирает журнал образцами.

local function esc(s)
	return (tostring(s):gsub("[\"\\]", "\\%0"))
end

function M.encode(state)
	state = state or M.newState()
	local names = {}
	for name in pairs(state.files or {}) do names[#names + 1] = name end
	table.sort(names)

	local parts = {}
	for _, name in ipairs(names) do
		local e = state.files[name]
		-- Имя экранируется тем же `esc`, а не `%q`: `%q` в Lua переносит строку
		-- обратным слэшем и переводом строки, а это уже не JSON.
		parts[#parts + 1] = string.format(
			'"%s":{"sent":%d,"head":"%s","lines":%d}',
			esc(name), math.floor(e.sent or 0), esc(e.head or ""), math.floor(e.lines or 0))
	end
	return '{"v":1,"files":{' .. table.concat(parts, ",") .. "}}"
end

function M.decode(text)
	local state = M.newState()
	if type(text) ~= "string" then return state end
	for name, sent, head, lines in
		text:gmatch('"([^"]+)":{"sent":(%d+),"head":"([^"]*)","lines":(%d+)}') do
		state.files[name] = {
			sent  = tonumber(sent) or 0,
			head  = head,
			lines = tonumber(lines) or 0,
		}
	end
	return state
end

return M
